test('LINE webhook authenticates the raw payload and discovers a group without changing the destination',async t=>{
  const directory=mkdtempSync(path.join(os.tmpdir(),'campus-api-test-'));
  const email='editor@example.org',password='fixture-passphrase-2026';
  const app=await createApp({directory,startWorker:false,bootstrapEmail:email,bootstrapPassword:password});
  const server=http.createServer(app.handler);
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  t.after(async()=>{
    server.closeAllConnections();
    await new Promise(resolve=>server.close(resolve));
    await app.close();
    if(path.dirname(directory)!==path.resolve(os.tmpdir())||!path.basename(directory).startsWith('campus-api-test-'))throw new Error('Unsafe cleanup');
    rmSync(directory,{recursive:true,force:true});
  });
  const base=`http://127.0.0.1:${server.address().port}`,secret='fixture-webhook-secret';
  app.store.setSecret('LINE_CHANNEL_SECRET',secret);
  const groupId='C'+'a'.repeat(32);
  const body=JSON.stringify({events:[{type:'join',source:{type:'group',groupId}}]});
  const signature=createHmac('sha256',secret).update(body).digest('base64');
  const send=value=>fetch(base+'/api/line/webhook',{method:'POST',headers:{'x-line-signature':value},body});
  assert.equal((await send('bad-signature')).status,401);
  assert.equal(app.store.kv('lineDiscoveredGroup'),null);
  assert.equal((await send(signature)).status,200);
  assert.equal(app.store.secret('LINE_GROUP_ID'),'');
  assert.equal((await fetch(base+'/api/line/discovered-group')).status,401);
  const login=await fetch(base+'/api/login',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({email,password})});
  const cookie=login.headers.get('set-cookie').split(';')[0];
  const response=await fetch(base+'/api/line/discovered-group',{headers:{cookie}});
  assert.deepEqual(await response.json(),{id:groupId});
});

